export function resolveInitialLanguage() {
  return "en";
}

export function persistLanguageChoice() {}

export function tr(_lang, key, vars = null) {
  let str = I18N.en[key] !== undefined ? I18N.en[key] : key;
  if (vars && typeof str === "string") {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}

export function getObjectName(obj) {
  if (!obj) return "";
  return obj.name_en || obj.name || obj.id;
}

export function getObjectHeadline(obj) {
  const sci = obj?.science || {};
  return sci.headline_en || sci.headline || obj.headline_en || obj.headline || "";
}

export function getObjectSummary(obj) {
  const sci = obj?.science || {};
  return sci.summary_en || sci.summary || sci.description_en || obj.summary_en || obj.summary || obj.description || "";
}

export function getCategoryLabel(catId, _lang, customCatMeta = null) {
  if (customCatMeta && customCatMeta.label_en) {
    return customCatMeta.label_en;
  }
  return tr("en", `cat_${catId}`);
}
